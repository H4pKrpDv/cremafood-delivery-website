/**
 * lib/useImageFallback.ts
 * ------------------------------------------------------------------
 * Graceful fallback битых <img> — React-версия того, что раньше делал
 * общий inline-скрипт в <head> (app/layout.tsx, добавлен 22.09.2026,
 * см. Context.md).
 *
 * ИСТОРИЯ ПОПЫТОК ЧИНИТЬ БАГ "битые картинки при переключении категорий"
 * (все три задокументированы в Context.md, 02.10.2026):
 *
 * Попытка 1 — перенос старого глобального document.addEventListener(
 * 'error', ..., true) на обычный React onError/useState на каждом <img>.
 * Убрала гонку с гидратацией (которая и правда была одной из причин), но
 * сам баг остался — по видео пользователя было видно, что уже однажды
 * показанная заглушка на повторном открытии вкладки на несколько секунд
 * снова становится нативной "битой иконкой".
 *
 * Попытка 2 — модульный кэш путей (knownBrokenSrcs), чтобы повторная
 * заглушка подставлялась мгновенно, без повторного реального запроса по
 * сети. Сама по себе эта оптимизация разумна (и оставлена ниже), но
 * пользователь перепроверил — не помогло. Решающая улика после этого:
 * на проде (где этот же код уже отработал на более старой/меньшей версии
 * меню) бага нет вообще, сброс кэша браузера локально тоже не помогает —
 * то есть дело не в браузерном кэше и не в самой React-логике.
 *
 * Попытка 3 — middleware.ts, отдававший лёгкий 404 для несуществующих
 * /img/items|categories/* до рендера тяжёлой app/not-found.tsx (теория:
 * в деве not-found.tsx рендерится заново на каждый из ~80 запросов). Тоже
 * не помогло — пользователь проверил и `next dev`, и `next start`
 * (production-сборка локально): оба ведут себя одинаково, а в DevTools
 * Network отдельные 404-ответы уже были быстрыми и ДО middleware. Значит,
 * узкое место не в скорости ответа сервера на один запрос.
 *
 * НАСТОЯЩАЯ ПРИЧИНА (01.10.2026): дело не в скорости ОДНОГО ответа, а в
 * количестве ОДНОВРЕМЕННЫХ запросов. Сейчас в public/ нет вообще ни
 * одной настоящей фотографии товара/подкатегории (см. generate-image-
 * manifest.mjs) — то есть ВСЕ ~80 путей (69 товаров + ~9 баннеров) при
 * открытии вкладки категории гарантированно ведут в никуда. Браузер
 * ограничивает число одновременных соединений к одному хосту (обычно 6
 * у HTTP/1.1) — именно так локально работает голый `next dev`/`next
 * start` (http://localhost без HTTP/2). Реальный хостинг продакшена
 * отдаёт по HTTP/2, где этого лимита по факту нет — отсюда и расхождение
 * "на проде бага нет, локально есть", и то, что `next dev`/`next start`
 * ведут себя одинаково (лимит — особенность браузера+протокола, а не
 * режима Next.js). Чем больше позиций в меню (а после актуализации их
 * стало заметно больше — отсюда и совпадение по времени с правкой
 * menu.json, при том что сама логика показа картинок не менялась), тем
 * длиннее очередь из запросов, которые просто ЖДУТ своей очереди на
 * соединение — всё это время <img> показывает нативную "битую иконку",
 * хотя КОНКРЕТНЫЙ ответ, когда до него доходит очередь, и правда быстрый
 * (это и видел пользователь в Network tab).
 *
 * Правильное исправление — не ПОРОЖДАТЬ эти обречённые запросы вообще.
 * lib/data.ts (hasRealImage) теперь знает ещё на этапе сборки/старта
 * сервера, для каких путей файл реально существует. Если файла нет —
 * сразу подставляем заглушку с первого рендера (и на сервере при SSR, и
 * на клиенте — манифест одинаковый), <img src> никогда не указывает на
 * несуществующий путь, и браузер вообще не делает сетевой запрос. Как
 * только для позиции появится настоящее фото — манифест на следующий
 * запуск подхватит это автоматически.
 *
 * onError/knownBrokenSrcs ниже остаются как защитный запасной вариант —
 * на случай, если файл по манифесту существует, но реально не грузится
 * (повреждён, не тот формат и т.п.) — тогда сработает ровно тот же
 * сценарий "ошибка -> заглушка -> запомнили -> больше не пробуем".
 * ------------------------------------------------------------------
 */

'use client';

import { useState } from 'react';

// Заглушка отсутствующего фото. САМА иконка "фото" (золотой контур на
// фоне --surface-2) рисуется теперь CSS-ом — классом .img-placeholder через
// переменную --placeholder-icon (globals.css, своё значение для каждой
// темы), а <img src> всегда получает ОДИН И ТОТ ЖЕ прозрачный SVG
// (пропорции 4:3 — те же, что были у прежней иконки, чтобы intrinsic-размер
// у <img> не менялся).
//
// Почему не data:-SVG с зашитыми цветами, выбираемый по теме в JS (так было
// 02–04.10.2026): значение темы в сторе до гидратации всегда дефолтное, и
// у пользователей с сохранённой тёмной темой заглушки на мгновение были бы
// светлыми — то же мигание, что и с самой темой (см. store/themeStore.ts).
// Через CSS заглушка меняется вместе с data-theme на <html> и вообще не
// зависит от JS/гидратации. Реальных фото пока почти ни у одной позиции
// меню нет (см. комментарий ниже про hasImage), так что заглушка — то, что
// видно почти везде, и мигать она не должна.
export const IMAGE_PLACEHOLDER_SRC =
  'data:image/svg+xml;charset=UTF-8,' +
  encodeURIComponent('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 4 3"/>');

// Общий на весь модуль (а значит — на все инстансы хука на странице) набор
// путей, про которые мы уже точно знаем, что реальная загрузка провалилась
// (запасной вариант для файлов, которые по манифесту существуют, но не
// грузятся по другой причине — см. комментарий в начале файла).
const knownBrokenSrcs = new Set<string>();

export interface ImageFallback {
  src: string;
  // Пустая строка, когда реальная картинка загружена/ещё не провалилась —
  // удобно подставлять через шаблонную строку без лишних пробелов-проверок
  // у вызывающего компонента.
  imgClassName: string;
  onError: () => void;
}

// hasImage — есть ли у realSrc реальный файл по данным lib/data.ts
// (hasRealImage), известно ещё до первого рендера (и на сервере, и на
// клиенте — манифест одинаковый). Когда hasImage === false, компонент
// рендерит заглушку сразу и <img> НИКОГДА не запрашивает realSrc по сети —
// это и устраняет сам источник бага (залповые ~80 обречённых запросов).
export function useImageFallback(realSrc: string, hasImage: boolean): ImageFallback {
  const [broken, setBroken] = useState(() => !hasImage || knownBrokenSrcs.has(realSrc));
  return {
    src: broken ? IMAGE_PLACEHOLDER_SRC : realSrc,
    imgClassName: broken ? 'img-placeholder' : '',
    onError: () => {
      knownBrokenSrcs.add(realSrc);
      setBroken(true);
    }
  };
}
